def main():
    if os.path.isdir(ROOT):
        shutil.rmtree(ROOT)
    os.makedirs(ROOT)
    with open(os.path.join(ROOT, "00_はじめに読んで.txt"), "w", encoding="utf-8-sig") as f:
        f.write(GUIDE)
    for p in PRODUCTS:
        d = os.path.join(ROOT, p["dir"])
        os.makedirs(os.path.join(d, "アップロードするzip"))
        os.makedirs(os.path.join(d, "画像_この順で登録"))
        for z in p["zips"]:
            shutil.copy(os.path.join(DIST, z), os.path.join(d, "アップロードするzip", z))
        for i, (lab, fn) in enumerate(p["images"]):
            shutil.copy(os.path.join(IMG, fn), os.path.join(d, "画像_この順で登録", "{}_{}.png".format(i + 1, lab)))
        desc = p["desc"].format(apps=APPS, terms=TERMS, set_link=SET_LINK)
        txt = ["【商品名】", p["title"], "",
               "【価格】", "{}円".format(p["price"]) if p["price"] else "0円（無料）", "",
               "【R18（18歳未満の閲覧に適さない）】", "チェックする" if p["r18"] else "チェックしない", "",
               "【カテゴリ】", "素材データ ＞ 素材（その他）", "",
               "【タグ】（1つずつ入力）", "\n".join(p["tags"]), "",
               "【ダウンロードファイル】（全部登録）", "\n".join(p["zips"]), "",
               "【商品説明】（ここから下を全部コピー）", "", desc, ""]
        with open(os.path.join(d, "出品情報.txt"), "w", encoding="utf-8-sig") as f:
            f.write("\n".join(txt))
        print(p["dir"])
    md = ["# 出品テキスト（BOOTH）", "", "※ BOOTH出品/ の各フォルダの「出品情報.txt」と同じ内容です。", ""]
    for p in PRODUCTS:
        md += ["---", "", "## " + p["dir"], "", "**商品名**：" + p["title"], "",
               "**価格**：{}円".format(p["price"]) + ("　**R18**" if p["r18"] else ""), "",
               "**タグ**：" + "、".join(p["tags"]), "", "**説明文**", "", "```",
               p["desc"].format(apps=APPS, terms=TERMS, set_link=SET_LINK), "```", ""]
    with open(os.path.join(HERE, "出品テキスト.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(md))


if __name__ == "__main__":
    main()
